            <p>
              Third Brigade, 25th Infantry Division, including the 2nd Battalion, 5th Infantry, was deployed to Afghanistan in April, 2004. Its mission was to deny sanctuary to the terrorists and to create the conditions for security, stability and reconstruction in the war-torn land. The battalion began its tour of duty in Ghazni Province but soon moved to Tirin Kot in Oruzgan Province. As in Vietnam, the components of battalion were usually dispersed.
            </p>
            <p>
              The first major task was to curtail efforts by the Taliban and other anti-coalition militia to disrupt the Afghan presidential election scheduled for October 9, 2004. Once the election was over, the operational emphasis was shifted to furnishing support for Afghan reconstruction and the training of Afghan security forces. There were also plenty of natural disasters in the mountainous country to keep the men of the battalion busy. Following Second Battalion’s return to Schofield Barracks in the spring of 2005, it was awarded the Meritorious Unit Commendation for its exemplary service in Afghanistan
            </p>
            
